"""Render .env-style text from VarSpecs."""
from __future__ import annotations

import re
from typing import List

from .schema import VarSpec

_PLAIN = re.compile(r"^[\w./:@%+,=-]*$")


def quote(value: str) -> str:
    """Quote a value only when .env parsers would otherwise misread it."""
    if _PLAIN.match(value):
        return value
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def env_line(spec: VarSpec) -> str:
    return f"{spec.key}={quote(spec.default)}"


def annotation(spec: VarSpec) -> str:
    parts = [spec.type]
    if spec.secret:
        parts.append("secret")
    if spec.required:
        parts.append("required")
    elif not spec.secret:
        parts.append(f"default: {spec.default or None}")
    text = f"# {spec.key} ({', '.join(parts)})"
    return f"{text} - {spec.description}" if spec.description else text


def render_example(specs: List[VarSpec], source: str, eol: str = "\n") -> str:
    blocks = [f"# Generated by envsync from {source}. Do not edit by hand."]
    blocks += [annotation(s) + eol + env_line(s) for s in specs]
    return (eol + eol).join(blocks) + eol
